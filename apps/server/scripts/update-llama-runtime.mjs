#!/usr/bin/env node
// Pin the managed llama.cpp runtime to one upstream build.
//
//   node apps/server/scripts/update-llama-runtime.mjs b11149
//
// Writes src/llama/runtime-manifest.ts with the sha256 of every asset the
// server may download, taken from GitHub's own asset digests. The server
// verifies each download against this file, so updating llama.cpp is always a
// reviewed change to a pinned build — never "whatever is latest" — because this
// is a binary the server executes.
//
// Needs the GitHub CLI (`gh`), authenticated or not (the repo is public).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const tag = process.argv[2];
if (!tag || !/^b\d+$/.test(tag)) {
  console.error("usage: update-llama-runtime.mjs <tag, e.g. b11149>");
  process.exit(1);
}

// Which asset each (platform, backend) pair resolves to is decided by the same
// table the version picker uses (src/llama/runtime-assets.ts), so the pinned
// build and an admin-chosen one can never disagree about a release's assets.
// Windows CUDA builds need the matching `cudart` archive unpacked beside them.
const { ASSET_SPECS, matchAssets } = await import("../src/llama/runtime-assets.ts");

const release = JSON.parse(
  execFileSync("gh", ["api", `repos/ggml-org/llama.cpp/releases/tags/${tag}`], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }),
);
const assets = release.assets.map((a) => ({ name: a.name, size: a.size, digest: typeof a.digest === "string" ? a.digest : null }));

const builds = {};
for (const key of Object.keys(ASSET_SPECS)) {
  const match = matchAssets(tag, assets, key);
  if (match.status === "no-build") throw new Error(`${tag} has no asset for ${key}`);
  if (match.status === "no-checksum") throw new Error(`${tag}'s asset for ${key} has no sha256 digest on GitHub`);
  builds[key] = match.build;
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/llama/runtime-manifest.ts");
writeFileSync(
  out,
  `// Generated by apps/server/scripts/update-llama-runtime.mjs — do not edit by hand.\n` +
    `// The one llama.cpp build this server will download, and the sha256 of every\n` +
    `// asset it may fetch. See the script for why this is pinned.\n\n` +
    `import type { RuntimeManifest } from "./runtime-types.ts";\n\n` +
    `export const RUNTIME_MANIFEST: RuntimeManifest = ${JSON.stringify({ tag, commit: release.target_commitish ?? null, builds }, null, 2)};\n`,
);
console.log(`wrote ${out} for ${tag} (${String(Object.keys(builds).length)} builds)`);
